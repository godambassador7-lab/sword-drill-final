/**
 * Get OT references for a given NT passage
 * @param {string} ntRef - NT reference (e.g., "Matthew 1:23")
 * @returns {Array} Array of OT quotation objects
 */
export function getOTQuotesForNT(ntRef) {
  return NT_QUOTES_OT.filter(q => q.nt === ntRef || q.nt.startsWith(ntRef.split(':')[0]));
}

/**
 * Get NT passages that quote a given OT passage
 * @param {string} otRef - OT reference (e.g., "Isaiah 7:14")
 * @returns {Array} Array of NT quotation objects
 */
export function getNTQuotesOfOT(otRef) {
  return NT_QUOTES_OT.filter(q => q.ot === otRef || q.ot.includes(otRef));
}

/**
 * Check if a passage has OT quotations/allusions
 * @param {string} ref - Bible reference
 * @returns {boolean}
 */
export function hasOTQuotes(ref) {
  return NT_QUOTES_OT.some(q => q.nt === ref || q.nt.startsWith(ref.split(':')[0]));
}

export default { NT_QUOTES_OT, getOTQuotesForNT, getNTQuotesOfOT, hasOTQuotes };
